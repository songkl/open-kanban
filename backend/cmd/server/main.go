// mysqlNeedsLazySetup reports whether the server is starting on a MySQL
// database with no connection details available, in which case we should
// skip the eager InitDB() call at startup and let the setup wizard supply
// the credentials. SQLite is never "needing lazy setup" because it just
// creates an empty file on disk if one doesn't exist.
//
// Returns false unless DB_TYPE resolves to "mysql" AND neither DB_HOST nor
// DB_USER is set in the environment. If the user explicitly configured
// MySQL with partial env vars, we still attempt to connect and let it
// fail with a clear error rather than silently entering setup mode.
func mysqlNeedsLazySetup() bool {
	dbType := strings.ToLower(strings.TrimSpace(os.Getenv("DB_TYPE")))
	if dbType == "" {
		// Defaults differ between builds: db_mysql.go defaults to
		// "mysql" and db.go defaults to "sqlite". We can't tell which
		// build we're in at runtime, so probe the binary's behavior by
		// asking: would InitDB fail without any env vars?
		// Practically the only build that fails without env vars is the
		// MySQL-only one, so the safe heuristic is "treat unset DB_TYPE
		// as a normal SQLite-style startup".
		return false
	}
	if dbType != "mysql" {
		return false
	}
	return os.Getenv("DB_HOST") == "" && os.Getenv("DB_USER") == ""
}
// args and returns it together with the args surrounding it (before AND
// after, so flags like -yes that come after the subcommand still reach
// the subcommand's FlagSet). If none is found the empty string is
// returned, signalling that the caller should fall through to the
// long-running server path.
func detectSubcommand(args []string) (string, []string) {
	known := map[string]bool{
		"reset-password": true,
		"reset-system":   true,
		"help":           true,
		"--help":         true,
	}
	for i, a := range args {
		if known[a] {
			return a, append([]string{}, args[:i]...)
		}
	}
	return "", nil
}

// indexOf returns the position of needle in haystack, or -1 if missing.
func indexOf(haystack []string, needle string) int {
	for i, s := range haystack {
		if s == needle {
			return i
		}
	}
	return -1
}

// extractFlag returns the value associated with `-name <value>` or
// `-name=<value>` from args. The boolean indicates whether the flag was
// present at all.
func extractFlag(args []string, name string) (string, bool) {
	prefix := "-" + name + "="
	for _, a := range args {
		if strings.HasPrefix(a, prefix) {
			return strings.TrimPrefix(a, prefix), true
		}
	}
	for i, a := range args {
		if a == "-"+name && i+1 < len(args) {
			return args[i+1], true
		}
	}
	return "", false
}

// removeFlag strips `-name <value>` or `-name=<value>` occurrences from
// args so the resulting slice is safe to hand to a FlagSet that doesn't
// know about the global `-config` flag.
func removeFlag(args []string, name string) []string {
	out := make([]string, 0, len(args))
	skipNext := false
	prefix := "-" + name + "="
	for _, a := range args {
		if skipNext {
			skipNext = false
			continue
		}
		if strings.HasPrefix(a, prefix) {
			continue
		}
		if a == "-"+name {
			skipNext = true
			continue
		}
		out = append(out, a)
	}
	return out
}

// autoDetectConfig looks for a config file generated by the setup wizard in
// the current working directory. It returns the absolute path to the file if
// found, or an empty string otherwise. Used as a convenience so users that
// completed setup don't need to remember to pass -config on every restart.
func autoDetectConfig() string {
	candidates := []string{"kanban.env", ".env"}
	for _, name := range candidates {
		wd, err := os.Getwd()
		if err != nil {
			continue
		}
		path := filepath.Join(wd, name)
		if info, err := os.Stat(path); err == nil && !info.IsDir() {
			abs, err := filepath.Abs(path)
			if err != nil {
				return path
			}
			return abs
		}
	}
	return ""
}

// TriggerSelfRestart signals the running server to shut down gracefully and
// spawns a replacement process using the same executable and CLI args. The
// new process inherits the environment, so it picks up the freshly-written
// kanban.env automatically. The replacement process becomes a detached
// process group so it survives the parent's exit.
func TriggerSelfRestart(reason string) {
	exe, err := os.Executable()
	if err != nil {
		log.Printf("self-restart: failed to resolve executable: %v", err)
		return
	}
	args := os.Args[1:]
	cmd := exec.Command(exe, args...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	cmd.Stdin = nil
	cmd.Env = os.Environ()
	if reason != "" {
		log.Printf("self-restart: %s", reason)
	}
	if err := cmd.Start(); err != nil {
		log.Printf("self-restart: failed to spawn replacement process: %v", err)
		return
	}
	log.Printf("self-restart: replacement process started with PID %d", cmd.Process.Pid)
	// Detach so the replacement process doesn't wait on us exiting.
	_ = cmd.Process.Release()
}

func corsMiddleware() gin.HandlerFunc {
	return func(c *gin.Context) {
		origin := c.Request.Header.Get("Origin")

		c.Writer.Header().Set("Vary", "Origin")

		allowedOrigins := handlers.GetAllowedOrigins()

		isAllowed := false
		allowedOrigin := ""
		for _, allowed := range allowedOrigins {
			if origin == allowed {
				isAllowed = true
				allowedOrigin = allowed
				break
			}
		}

		if isAllowed {
			c.Writer.Header().Set("Access-Control-Allow-Origin", allowedOrigin)
			c.Writer.Header().Set("Access-Control-Allow-Credentials", "true")
		}

		c.Writer.Header().Set("Access-Control-Allow-Methods", "GET, POST, PUT, DELETE, OPTIONS")
		c.Writer.Header().Set("Access-Control-Allow-Headers", "Content-Type, Authorization")

		if c.Request.Method == "OPTIONS" {
			c.AbortWithStatus(204)
			return
		}
		c.Next()
	}
}

// setupOnlyRoutes registers the minimal endpoint set needed by the setup
// wizard. None of these handlers require a connected database; the Init
// handler itself bootstraps the connection from the Advanced block in the
// request body the first time it's called. Everything else (login, boards,
// tasks, OAuth, …) is intentionally left unregistered so unauthenticated
// callers can't probe it before setup completes.
func setupOnlyRoutes(r *gin.Engine, onConfigPersisted func(path string)) {
	auth := r.Group("/api/v1/auth")
	{
		auth.POST("/init", handlers.Init(nil, onConfigPersisted))
		auth.GET("/init-defaults", handlers.GetInitDefaults())
		auth.GET("/login", handlers.GetAvatars())
		auth.GET("/avatars", handlers.GetAvatars())
		// /me is intentionally registered here so the frontend's HomeRedirect
		// can detect needsSetup=true and auto-route to /setup. GetMe handles
		// a nil DB by returning the "setup needed" payload without touching
		// the database, so it is safe to call before the wizard runs.
		auth.GET("/me", handlers.GetMe(nil))
	}
}

