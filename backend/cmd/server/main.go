func setupStaticRoutes(r *gin.Engine, webDir string, embeddedWeb embed.FS) {
	mimeTypes := map[string]string{
		".js":    "application/javascript",
		".css":   "text/css",
		".html":  "text/html",
		".json":  "application/json",
		".png":   "image/png",
		".jpg":   "image/jpeg",
		".svg":   "image/svg+xml",
		".ico":   "image/x-icon",
		".woff":  "font/woff",
		".woff2": "font/woff2",
	}

	getMimeType := func(path string) string {
		ext := ""
		if i := strings.LastIndex(path, "."); i > 0 {
			ext = path[i:]
		}
		if mime, ok := mimeTypes[ext]; ok {
			return mime
		}
		return "application/octet-stream"
	}

	validExts := map[string]bool{
		".js": true, ".css": true, ".png": true, ".jpg": true, ".jpeg": true,
		".svg": true, ".ico": true, ".woff": true, ".woff2": true, ".ttf": true,
		".eot": true, ".otf": true, ".webp": true, ".gif": true, ".webm": true,
		".mp4": true, ".wav": true, ".mp3": true,
	}

	isValidAsset := func(ext string) bool {
		return validExts[ext]
	}

	if webDir == "" {
		subFS, err := fs.Sub(embeddedWeb, "web")
		if err != nil {
			log.Fatal("Failed to access embedded web filesystem:", err)
		}

		r.GET("/", func(c *gin.Context) {
			f, err := subFS.Open("index.html")
			if err != nil {
				c.String(404, "index.html not found")
				return
			}
			defer f.Close()
			c.Header("Cache-Control", "no-cache")
			c.Header("Content-Type", "text/html; charset=utf-8")
			if _, err := io.Copy(c.Writer, f); err != nil {
				c.String(500, "Failed to serve file")
			}
		})

		r.GET("/assets/*path", func(c *gin.Context) {
			path := strings.TrimPrefix(c.Param("path"), "/")
			ext := ""
			if i := strings.LastIndex(path, "."); i > 0 {
				ext = path[i:]
			}
			if !isValidAsset(ext) {
				c.JSON(404, gin.H{"error": "Not found"})
				return
			}
			f, err := subFS.Open("assets/" + path)
			if err != nil {
				c.String(404, "file not found")
				return
			}
			defer f.Close()
			c.Header("Content-Type", getMimeType(path))
			if _, err := io.Copy(c.Writer, f); err != nil {
				c.String(500, "Failed to serve file")
			}
		})

		r.NoRoute(func(c *gin.Context) {
			path := c.Request.URL.Path
			if strings.HasPrefix(path, "/api/") || strings.HasPrefix(path, "/ws") {
				c.JSON(404, gin.H{"error": "Not found"})
				return
			}
			f, err := subFS.Open("index.html")
			if err != nil {
				c.String(404, "index.html not found")
				return
			}
			defer f.Close()
			c.Status(200)
			c.Header("Cache-Control", "no-cache")
			c.Header("Content-Type", "text/html; charset=utf-8")
			if _, err := io.Copy(c.Writer, f); err != nil {
				c.String(500, "Failed to serve file")
			}
		})
	} else {
		r.GET("/", func(c *gin.Context) {
			c.File(webDir + "/index.html")
		})

		r.GET("/assets/*path", func(c *gin.Context) {
			path := c.Param("path")
			ext := ""
			if i := strings.LastIndex(path, "."); i > 0 {
				ext = path[i:]
			}
			if !isValidAsset(ext) {
				c.JSON(404, gin.H{"error": "Not found"})
				return
			}
			c.File(webDir + "/assets/" + path)
		})

		r.NoRoute(func(c *gin.Context) {
			path := c.Request.URL.Path
			if strings.HasPrefix(path, "/api/") || strings.HasPrefix(path, "/ws") {
				c.JSON(404, gin.H{"error": "Not found"})
				return
			}
			c.File(webDir + "/index.html")
		})
	}
}

func main() {
	// CLI commands
	resetPasswordCmd := flag.NewFlagSet("reset-password", flag.ExitOnError)
	userNickname := resetPasswordCmd.String("user", "", "User nickname")
	newPassword := resetPasswordCmd.String("password", "", "New password")

	resetSystemCmd := flag.NewFlagSet("reset-system", flag.ExitOnError)
	resetSystemYes := resetSystemCmd.Bool("yes", false, "Skip the interactive confirmation prompt")

	configFilePath := flag.String("config", "", "Path to config file (reads env vars from file)")

	// If a subcommand is present, route to its handler before any long-running
	// setup (config load, DB init, HTTP server) so reset / help never start a
	// server. The subcommand can also receive `-config` to know which DB to
	// connect to.
	if subcommand, _ := detectSubcommand(os.Args[1:]); subcommand != "" {
		// Compute subArgs from the post-flag-removal slice so indices stay
		// accurate when `-config` is stripped out.
		fullArgs := append([]string{}, os.Args[1:]...)
		if v, ok := extractFlag(fullArgs, "config"); ok {
			*configFilePath = v
			fullArgs = removeFlag(fullArgs, "config")
		}
		if *configFilePath != "" {
			log.Printf("Loading config from: %s", *configFilePath)
			if err := loadEnvFromFile(*configFilePath); err != nil {
				log.Fatalf("Failed to load config file: %v", err)
			}
		} else if autoConfigPath := autoDetectConfig(); autoConfigPath != "" {
			log.Printf("Auto-loading config from: %s", autoConfigPath)
			if err := loadEnvFromFile(autoConfigPath); err != nil {
				log.Fatalf("Failed to load auto-detected config file: %v", err)
			}
		}
		// Drop the subcommand itself; the remaining args (before + after)
		// are what the subcommand's FlagSet should see.
		idx := indexOf(fullArgs, subcommand)
		var subArgs []string
		if idx > 0 {
			subArgs = append(subArgs, fullArgs[:idx]...)
		}
		if idx+1 < len(fullArgs) {
			subArgs = append(subArgs, fullArgs[idx+1:]...)
		}
		switch subcommand {
		case "reset-password":
			resetPasswordCmd.Parse(subArgs)
			if *userNickname == "" || *newPassword == "" {
				fmt.Println("Usage: kanban-server reset-password -user <nickname> -password <newpassword>")
				os.Exit(1)
			}
			runPasswordReset(*userNickname, *newPassword)
			return
		case "reset-system":
			resetSystemCmd.Parse(subArgs)
			runSystemReset(*resetSystemYes)
			return
		case "help", "--help":
			printUsage()
			return
		}
	}

	flag.Parse()

	if *configFilePath != "" {
		log.Printf("Loading config from: %s", *configFilePath)
		if err := loadEnvFromFile(*configFilePath); err != nil {
			log.Fatalf("Failed to load config file: %v", err)
		}
	} else if autoConfigPath := autoDetectConfig(); autoConfigPath != "" {
		log.Printf("Auto-loading config from: %s", autoConfigPath)
		if err := loadEnvFromFile(autoConfigPath); err != nil {
			log.Fatalf("Failed to load auto-detected config file: %v", err)
		}
	}

	// Initialize config
	config.InitConfig()

	// First-run / lazy-setup: if the binary is the MySQL-only build and no
	// DB credentials are configured, skip the eager database.InitDB() call
	// here. The HTTP server will still come up, register only the setup
	// routes (Init / InitDefaults / Avatars), and let the setup wizard
	// supply DB credentials via the Advanced block. The Init handler then
	// bootstraps the connection itself, writes kanban.env, and triggers a
	// self-restart so the next startup loads the persisted config normally.
	var db *sql.DB
	if mysqlNeedsLazySetup() {
		log.Println("=================================================================")
		log.Println(" No MySQL connection details found in the environment.")
		log.Println(" Starting in setup mode. Open this server's URL in a browser to")
		log.Println(" complete the setup wizard and provide database credentials.")
		log.Println("=================================================================")
	} else {
		var err error
		db, err = database.InitDB()
		if err != nil {
			log.Fatal("Failed to initialize database:", err)
		}
	}

	// Initialize webhook service
	services.InitWebhookService()

	// Create Gin router
	r := gin.New()

	// Structured logging middleware
	r.Use(handlers.RequestLoggerMiddleware())

	// Global rate limiting middleware
	r.Use(handlers.GlobalRateLimitMiddleware())

	// Compression middleware for API responses
	r.Use(handlers.CompressionMiddleware())

	// CORS middleware
	r.Use(corsMiddleware())

	// Health check endpoint (public, no auth required)
	r.GET("/api/v1/health", handlers.HealthCheck)
	r.GET("/api/v1/status", handlers.HealthCheck)

	// Setup API routes. The init endpoint can request a self-restart once the
	// setup wizard finishes writing kanban.env, so we forward a callback that
	// signals the HTTP server to shut down and spawn a replacement process.
	restartCh := make(chan string, 1)
	onConfigPersisted := func(path string) {
		select {
		case restartCh <- path:
		default:
		}
	}
	if db == nil {
		// First-run / lazy-setup: only the endpoints required by the setup
		// wizard are reachable. Everything else (login, boards, tasks, …)
		// requires a connected DB and will return 404 until the wizard
		// completes and the process restarts with the persisted config.
		setupOnlyRoutes(r, onConfigPersisted)
	} else {
		setupAPIRoutes(r, db, onConfigPersisted)
	}

	// Static files - serve embedded frontend by default, or from WEB_DIR if set
	webDir := os.Getenv("WEB_DIR")

	if webDir != "" {
		if _, err := os.Stat(webDir); err != nil {
			log.Printf("Warning: Web directory not found at %s, falling back to embedded web", webDir)
			webDir = ""
		}
	}

	useEmbedded := webDir == ""
	if useEmbedded {
		log.Println("Serving embedded web assets")
	} else {
		log.Printf("Serving static files from: %s", webDir)
	}

	setupStaticRoutes(r, webDir, embeddedWeb)

	// Get port from env
	port := os.Getenv("PORT")
	if port == "" {
		port = "8080"
	}

	// Print startup banner
	fmt.Println("")
	fmt.Println(`   dP"Yb  88""Yb 888888 88b 88     88  dP    db    88b 88 88""Yb    db    88b 88 `)
	fmt.Println(`  dP   Yb 88__dP 88__   88Yb88     88odP    dPYb   88Yb88 88__dP   dPYb   88Yb88 `)
	fmt.Println(`  Yb   dP 88"""  88""   88 Y88     88"Yb   dP__Yb  88 Y88 88""Yb  dP__Yb  88 Y88 `)
	fmt.Println(`   YbodP  88     888888 88  Y8     88  Yb dP""""Yb 88  Y8 88oodP dP""""Yb 88  Y8 `)
	fmt.Println("")
	fmt.Println("  https://github.com/songkl/open-kanban")
	fmt.Println("")
	fmt.Println("")
	log.Printf("Server starting on port %s", port)

	httpServer := &http.Server{
		Addr:    ":" + port,
		Handler: r,
	}

	// Wire graceful shutdown so the self-restart path can stop accepting
	// connections cleanly before the replacement process binds the port.
	shutdownSignal := make(chan os.Signal, 1)
	signal.Notify(shutdownSignal, syscall.SIGINT, syscall.SIGTERM)
	shutdownHTTP := func(reason string) {
		log.Printf("Shutting down HTTP server (%s)...", reason)
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		if err := httpServer.Shutdown(shutdownCtx); err != nil {
			log.Printf("HTTP server shutdown error: %v", err)
		}
	}
	go func() {
		select {
		case <-shutdownSignal:
			shutdownHTTP("signal received")
		case path := <-restartCh:
			TriggerSelfRestart(fmt.Sprintf("config written to %s by setup wizard", path))
			shutdownHTTP("self-restart requested")
		}
	}()

	if err := httpServer.ListenAndServe(); err != nil && err != http.ErrServerClosed {
		log.Fatal("Failed to start server:", err)
	}
	log.Println("HTTP server stopped")
}

