func runPasswordReset(nickname, newPassword string) {
	db, err := database.InitDB()
	if err != nil {
		log.Fatal("Failed to initialize database:", err)
	}
	defer db.Close()

	// Hash password with salt
	hashedPassword, err := handlers.HashPasswordWithSalt(newPassword)
	if err != nil {
		log.Fatal("Failed to hash password:", err)
	}

	result, err := db.Exec("UPDATE users SET password = ?, updated_at = datetime('now') WHERE nickname = ?", hashedPassword, nickname)
	if err != nil {
		log.Fatal("Failed to update password:", err)
	}

	rowsAffected, _ := result.RowsAffected()
	if rowsAffected == 0 {
		log.Fatal("User not found: ", nickname)
	}

	fmt.Printf("Password reset successfully for user: %s\n", nickname)
}

// runSystemReset wipes all user accounts and tokens so the setup wizard can
// be re-run from scratch. FK constraints cascade so dependent rows in
// board_permissions / activities / column_permissions / tokens go away
// with the users. App config is cleared so the next init starts from
// defaults (allowRegistration=true, requirePassword=password-present,
// authEnabled=true).
func runSystemReset(skipConfirm bool) {
	if !skipConfirm {
		fmt.Println("This will DELETE ALL users, tokens, and app config.")
		fmt.Println("After this completes, the setup wizard will re-create the first admin user.")
		fmt.Print("Type 'yes' to continue: ")
		var input string
		_, _ = fmt.Scanln(&input)
		if input != "yes" {
			fmt.Println("Aborted.")
			return
		}
	}

	db, err := database.InitDB()
	if err != nil {
		log.Fatal("Failed to connect to database: ", err)
	}
	defer db.Close()

	tables := []string{
		"tokens",
		"app_config",
		"users",
	}
	for _, table := range tables {
		if _, err := db.Exec(fmt.Sprintf("DELETE FROM %s", table)); err != nil {
			log.Fatalf("Failed to clear %s: %v", table, err)
		}
	}

	fmt.Println("System reset complete. Restart the server (or refresh /setup) to create a new admin user.")
}
